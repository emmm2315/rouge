package com.phantomcorridor.model;

/**
 * 房间类型枚举（对应新需求 §10 核心数据模型约定 RoomType，§5.2 房间类型）。
 *
 * <p>每层由若干房间节点组成（节点图，§5.1）；不同类型房间承载不同玩法：
 * 入口为出生点、战斗房清怪后出宝箱、奖励房直接给道具、商店消耗金币、
 * 事件房触发祝福/诅咒、Boss 房为当前层最终战斗区域。
 */
public enum RoomType {

    /** 入口：本层出生点，安全（§5.2） */
    ENTRANCE,

    /** 战斗房：有敌人，清理后奖励宝箱（§5.2） */
    BATTLE,

    /** 奖励房：无敌人，直接提供随机道具/金币（§5.2） */
    REWARD,

    /** 商店：消耗金币购买道具（§5.2） */
    SHOP,

    /** 事件房：随机事件，如选择祝福或诅咒（§5.2） */
    EVENT,

    /** 形态限定的隐藏路线房。 */
    HIDDEN,

    /** Boss 房：当前层最终战斗区域（§5.2） */
    BOSS
}
